using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax; // has syntax nodes (building blocks of Roslyn - represents elements in source code as tree)
using System.Collections.Immutable; // immutable types cannot be changed - makes the generator deterministic and safe 
using System.Linq; // Makes the generator pipeline simpler (more readable code than using foreach loops)
using System.Reflection.Metadata;
using System.Text; // Used for string builder when building generated code

/*
    A syntax node is apart of a tree representation of my source code (pieces of code become a node)
*/

namespace DictionarySourceGenerator;

[Generator] // attribute
public class DictionarySourceGenerator : IIncrementalGenerator // Roslyn generator model, builds output in reusable steps and reruns changes only
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // STEP ONE: GET CLASS DECLARATIONS (SYNTAX NODES) THE GENERATOR CAN PROCESS
        IncrementalValuesProvider<ClassDeclarationSyntax?> instructionClasses =
            context.SyntaxProvider.CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax, // Scans for nodes with a class declaration syntax
                transform: static (ctx, _) => // ctx = Context, this function calls the predicate above essentially
                {
                    ClassDeclarationSyntax? classDeclaration = (ClassDeclarationSyntax)ctx.Node;
                    bool hasAttribute = classDeclaration.AttributeLists.Any(attributeList => attributeList.Attributes.Any(attribute => attribute.Name.ToString() == "GenerateCommandRegistry"));
                    return hasAttribute ? classDeclaration : null; // Returns whether or not the class found the GenerateCommandRegistry attribute
                }
            ).Where(static classDeclaration => classDeclaration is not null); // Filters out classes that do not have ICommandMarker

        // STEP TWO: FILTER OUTPUT AND GENERATE CODE
        context.RegisterSourceOutput(instructionClasses.Collect(), static (sourceProductionContext, classes) => // Static will remove the need for an outer variable (essentially truly allowing this to run at compile time)
        {
            IEnumerable<string> entries = classes.Select(cls => cls.Identifier.Text)/*Gets class name*/
                                                .Distinct()/*Removes duplicates*/
                                                .Select(name => $"{{\"{name}\", (commandBytes) => new {name}(commandBytes) }}");
            string source = $$"""
            // <auto-generated />
            using System;
            using System.Collections.Generic; 
            using SharedDomainTypes;

            namespace Generated
            {
                public static class CommandRegistry
                {
                    public static IReadOnlyDictionary<string, Func<List<byte>, CommandTemplate>> Map { get; } = new Dictionary<string, Func<List<byte>, CommandTemplate>>
                    { 
                        {{string.Join(",\n            ", entries)}}
                    };
                }
            }
            """;
            sourceProductionContext.AddSource("CommandRegistry.g.cs", source);
        });
        ;
    }
}

public class SourceGenerator
{
    DictionarySourceGenerator gen = new DictionarySourceGenerator();
    
}
